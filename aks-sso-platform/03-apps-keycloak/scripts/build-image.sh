#!/usr/bin/env bash
# Build the launchpad container image. Default: `az acr build` — the build runs inside Azure Container Registry,
# so no local Docker, JDK or Gradle is needed (the Dockerfile's multi-stage build compiles the Spring Boot app).
#
#   scripts/build-image.sh [--acr NAME] [--tag 1.0.0] [--local] [--no-cache]
#
#   --acr    registry name (default: the one 01-infra created, from ../.platform/infra.env)
#   --tag    image tag (default: version from launchpad/gradle.properties or 1.0.0, plus a `latest` alias)
#   --local  build with Docker on this machine and push (needs docker + az acr login)
#
# Records the image in ../.platform/launchpad-image.env for scripts/install.sh.
source "$(dirname "$0")/lib.sh"
ACR="${ACR:-}"; TAG="${TAG:-}"; LOCAL=0; NOCACHE=""
while [ $# -gt 0 ]; do
  case "$1" in --acr) ACR="$2"; shift ;; --tag) TAG="$2"; shift ;; --local) LOCAL=1 ;; --no-cache) NOCACHE="--no-cache" ;; -h|--help) sed -n '2,11p' "$0"; exit 0 ;; *) die "unknown flag $1" ;; esac; shift
done
need az
az account show >/dev/null 2>&1 || die "not logged in: az login"
[ -z "$ACR" ] && [ -f "$INFRA_ENV" ] && ACR="$(sed -n 's/^ACR_NAME=//p' "$INFRA_ENV" | head -1)"
[ -n "$ACR" ] || die "which registry?  --acr <name>   (01-infra creates one: terraform output acr_name)"
az acr show -n "$ACR" >/dev/null 2>&1 || die "ACR '$ACR' not found or no access"
LOGIN="$(az acr show -n "$ACR" --query loginServer -o tsv)"
[ -n "$TAG" ] || TAG="$(sed -n 's/^appVersion=//p' "$DIR/launchpad/gradle.properties" | head -1)"; TAG="${TAG:-1.0.0}"
IMAGE="$LOGIN/launchpad:$TAG"
info "building ${c_bold}$IMAGE${c_off} from $DIR/launchpad (Dockerfile: multi-stage, JDK 25 → JRE 25)"

if [ "$LOCAL" = 1 ]; then
  need docker
  run az acr login -n "$ACR"
  run docker build $NOCACHE --build-arg "APP_VERSION=$TAG" -t "$IMAGE" -t "$LOGIN/launchpad:latest" "$DIR/launchpad"
  run docker push "$IMAGE"; run docker push "$LOGIN/launchpad:latest"
else
  # ACR Tasks: uploads the context (respecting .dockerignore) and builds in Azure. ~4-6 minutes the first time.
  run az acr build --registry "$ACR" --image "launchpad:$TAG" --image "launchpad:latest" $NOCACHE \
      --build-arg "APP_VERSION=$TAG" --file "$DIR/launchpad/Dockerfile" "$DIR/launchpad"
fi
az acr repository show-tags -n "$ACR" --repository launchpad -o tsv | grep -qx "$TAG" && ok "pushed $IMAGE" || die "image tag $TAG not visible in $ACR after the build"
mkdir -p "$HANDOFF_DIR"; { echo "# generated by 03-apps-keycloak/scripts/build-image.sh — $(date -u +%FT%TZ)"; echo "IMAGE=$IMAGE"; echo "ACR_NAME=$ACR"; } > "$IMAGE_ENV"
ok "recorded in $IMAGE_ENV"
echo "    next: scripts/install.sh            (or, if Keycloak is already installed: scripts/install.sh --launchpad-only)"
echo "    rollout a new tag later: scripts/build-image.sh --tag 1.0.1 && scripts/install.sh --launchpad-only --image $LOGIN/launchpad:1.0.1"
