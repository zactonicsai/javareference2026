# shellcheck shell=bash
# Shared helpers for 02-istio-gateway scripts. Source it; do not run it.
set -eo pipefail
if [ "${BASH_VERSINFO[0]}" -gt 4 ] || { [ "${BASH_VERSINFO[0]}" -eq 4 ] && [ "${BASH_VERSINFO[1]}" -ge 4 ]; }; then set -u; fi

DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"          # 02-istio-gateway
PLATFORM_ROOT="$(cd "$DIR/.." && pwd)"
HANDOFF_DIR="$PLATFORM_ROOT/.platform"
INFRA_ENV="$HANDOFF_DIR/infra.env"        # written by 01-infra (optional)
GATEWAY_ENV="$HANDOFF_DIR/gateway.env"    # written here for 03-apps-keycloak (optional)
AUTO_TFVARS="$DIR/generated.auto.tfvars"  # inputs resolved by apply.sh (git-ignored)
LOG="$DIR/.terraform-last-run.log"
YES="${YES:-0}"

c_bold=$'\e[1m'; c_dim=$'\e[2m'; c_ok=$'\e[32m'; c_warn=$'\e[33m'; c_err=$'\e[31m'; c_off=$'\e[0m'
info() { echo "${c_bold}==>${c_off} $*"; }
ok()   { echo "${c_ok}  ✓${c_off} $*"; }
warn() { echo "${c_warn}  !${c_off} $*"; }
fail() { echo "${c_err}  ✗${c_off} $*"; }
die()  { echo "${c_err}error:${c_off} $*" >&2; exit 1; }
run()  { echo "${c_dim}  \$ $*${c_off}"; "$@"; }
need() { for b in "$@"; do command -v "$b" >/dev/null 2>&1 || die "'$b' is required but not on PATH"; done; }
confirm() { [ "$YES" = 1 ] && return 0; [ -t 0 ] || die "non-interactive shell: re-run with --yes"; read -r -p "    $1 [y/N] " a; [[ "$a" =~ ^[Yy]$ ]] || die "aborted"; }

az_session() {
  need az
  az account show >/dev/null 2>&1 || die "not logged in to Azure: run  az login"
  ARM_SUBSCRIPTION_ID="$(az account show --query id -o tsv)"; export ARM_SUBSCRIPTION_ID
  info "Azure subscription: ${c_bold}$(az account show --query name -o tsv)${c_off} ${c_dim}($ARM_SUBSCRIPTION_ID)${c_off}"
}

tf() { ( cd "$DIR" && terraform "$@" ); }
tf_init() {
  need terraform
  if [ ! -d "$DIR/.terraform" ] || [ "${UPGRADE:-0}" = 1 ]; then
    run tf init -input=false -upgrade="$([ "${UPGRADE:-0}" = 1 ] && echo true || echo false)" >/dev/null
  fi
}
tf_out() { tf output -raw "$1" 2>/dev/null || true; }

# ---- inputs: flags > env > existing generated.auto.tfvars > ../.platform/infra.env > terraform.tfvars ----------
load_infra_env() { [ -f "$INFRA_ENV" ] && { set +u 2>/dev/null; source "$INFRA_ENV"; ok "using 01-infra hand-off ($INFRA_ENV)"; }; return 0; }
tfvar_from_file() {  # $1 file $2 key  -> value of  key = "value"  (or empty)
  [ -f "$1" ] || return 0
  sed -nE "s/^[[:space:]]*$2[[:space:]]*=[[:space:]]*\"?([^\"#]*)\"?.*$/\1/p" "$1" | head -1 | sed 's/[[:space:]]*$//'
}
resolve_inputs() {
  local prev_rg prev_cl; prev_rg="$(tfvar_from_file "$AUTO_TFVARS" resource_group_name)"; prev_cl="$(tfvar_from_file "$AUTO_TFVARS" cluster_name)"
  RESOURCE_GROUP="${RESOURCE_GROUP:-$prev_rg}"
  CLUSTER_NAME="${CLUSTER_NAME:-$prev_cl}"
  if [ "$RESOURCE_GROUP" = "$prev_rg" ] && [ "$CLUSTER_NAME" = "$prev_cl" ]; then   # same cluster as last run: reuse its IP settings
    PUBLIC_IP_NAME="${PUBLIC_IP_NAME:-$(tfvar_from_file "$AUTO_TFVARS" public_ip_name)}"
    PUBLIC_IP_RESOURCE_GROUP="${PUBLIC_IP_RESOURCE_GROUP:-$(tfvar_from_file "$AUTO_TFVARS" public_ip_resource_group)}"
    ALLOWED_SOURCE_CIDRS="${ALLOWED_SOURCE_CIDRS:-$(sed -nE 's/^[[:space:]]*allowed_source_cidrs[[:space:]]*=[[:space:]]*\[(.*)\].*$/\1/p' "$AUTO_TFVARS" 2>/dev/null | tr -d '" ')}"
  fi
  if [ -z "$RESOURCE_GROUP" ] || [ -z "$CLUSTER_NAME" ]; then
    local rg cl pip piprg
    rg="$(tfvar_from_file "$DIR/terraform.tfvars" resource_group_name)"; cl="$(tfvar_from_file "$DIR/terraform.tfvars" cluster_name)"
    pip="$(tfvar_from_file "$DIR/terraform.tfvars" public_ip_name)"; piprg="$(tfvar_from_file "$DIR/terraform.tfvars" public_ip_resource_group)"
    if [ -n "$rg" ] && [ -n "$cl" ]; then
      RESOURCE_GROUP="$rg"; CLUSTER_NAME="$cl"; PUBLIC_IP_NAME="${PUBLIC_IP_NAME:-$pip}"; PUBLIC_IP_RESOURCE_GROUP="${PUBLIC_IP_RESOURCE_GROUP:-$piprg}"
    else
      local _rg="$RESOURCE_GROUP" _cl="$CLUSTER_NAME" _pip="$PUBLIC_IP_NAME" _piprg="$PUBLIC_IP_RESOURCE_GROUP" _cidrs="${ALLOWED_SOURCE_CIDRS:-}"
      load_infra_env
      RESOURCE_GROUP="${_rg:-${RESOURCE_GROUP:-}}"; CLUSTER_NAME="${_cl:-${CLUSTER_NAME:-}}"
      PUBLIC_IP_NAME="${_pip:-${PUBLIC_IP_NAME:-}}"; PUBLIC_IP_RESOURCE_GROUP="${_piprg:-${PUBLIC_IP_RESOURCE_GROUP:-}}"
      ALLOWED_SOURCE_CIDRS="${_cidrs:-${ALLOWED_SOURCE_CIDRS:-}}"
    fi
  fi
  [ -n "${RESOURCE_GROUP:-}" ] && [ -n "${CLUSTER_NAME:-}" ] || die "which cluster?  scripts/apply.sh --rg <resource group> --cluster <name>   (or run 01-infra first)"
}

write_auto_tfvars() {
  local cidrs="${ALLOWED_SOURCE_CIDRS:-0.0.0.0/0}" list
  list="$(echo "$cidrs" | tr ',' '\n' | sed '/^$/d' | sed 's/.*/"&"/' | paste -sd, - | sed 's/,/, /g')"; list="[$list]"
  cat > "$AUTO_TFVARS" <<EOF
# generated by scripts/apply.sh — edit terraform.tfvars for permanent settings, flags/env for one-offs
resource_group_name      = "$RESOURCE_GROUP"
cluster_name             = "$CLUSTER_NAME"
public_ip_name           = "${PUBLIC_IP_NAME:-}"
public_ip_resource_group = "${PUBLIC_IP_RESOURCE_GROUP:-}"
allowed_source_cidrs     = $list
EOF
  ok "inputs → $AUTO_TFVARS"
}

ensure_kubecontext() {
  need kubectl
  if ! kubectl config get-contexts -o name 2>/dev/null | grep -qx "$CLUSTER_NAME"; then
    info "fetching kubeconfig for $CLUSTER_NAME"
    run az aks get-credentials -g "$RESOURCE_GROUP" -n "$CLUSTER_NAME" --overwrite-existing >/dev/null
  fi
  kubectl config use-context "$CLUSTER_NAME" >/dev/null
  kubectl get --raw=/readyz >/dev/null 2>&1 || die "cannot reach the API server of $CLUSTER_NAME (stopped? authorized IP ranges?)"
}

explain_failure() {
  [ -f "$LOG" ] || return 0
  echo; fail "terraform failed — hints:"
  grep -qi "no such host\|lookup.*blob.istio.io\|failed to fetch\|404 Not Found" "$LOG" && echo "    • Helm repo/version problem: check istio_version against https://istio.io/latest/news/releases/ and that $DIR can reach blob.istio.io"
  grep -qi "LinkedAuthorizationFailed\|does not have authorization\|PublicIPAddress.*not found\|cannot be used with LB" "$LOG" && echo "    • the cluster identity cannot use the public IP: it needs Network Contributor on the IP's resource group (01-infra does this). Or leave public_ip_name empty to create an IP in the node RG."
  grep -qi "timed out waiting for the condition\|context deadline exceeded" "$LOG" && echo "    • a release did not become ready in time: kubectl -n istio-ingress get pods,svc ; kubectl -n istio-ingress describe svc  (look for LB events) ; then re-run"
  grep -qi "Unauthorized\|x509\|certificate signed by unknown" "$LOG" && echo "    • kubeconfig credentials from the data source are not accepted: local accounts disabled? set disable_local_accounts=false in 01-infra or use kubelogin"
  grep -qi "another operation (install/upgrade/rollback) is in progress" "$LOG" && echo "    • a previous Helm run was interrupted: helm -n <ns> rollback <release> or helm -n <ns> uninstall <release>, then re-run"
  grep -qi "cannot re-use a name that is still in use" "$LOG" && echo "    • a release with that name already exists outside Terraform: helm list -A ; uninstall it or import it"
  echo "    full log: $LOG"
}

write_gateway_env() {
  mkdir -p "$HANDOFF_DIR"
  cat > "$GATEWAY_ENV" <<EOF
# generated by 02-istio-gateway/scripts/apply.sh — $(date -u +%FT%TZ)
RESOURCE_GROUP=$RESOURCE_GROUP
CLUSTER_NAME=$CLUSTER_NAME
PUBLIC_IP=$(tf_out public_ip)
PUBLIC_FQDN=$(tf_out public_fqdn)
PUBLIC_URL=$(tf_out public_url)
GATEWAY=$(tf_out gateway)
ISTIO_NAMESPACE=$(tf_out istio_namespace)
INGRESS_NAMESPACE=$(tf_out ingress_namespace)
TLS_SECRET=$(tf_out tls_secret)
CERT_FILE=$DIR/gateway.crt
EOF
  chmod 600 "$GATEWAY_ENV"; ok "hand-off written: $GATEWAY_ENV"
}
