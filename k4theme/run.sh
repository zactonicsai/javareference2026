#!/usr/bin/env bash
# =============================================================================
# run.sh -- create .env with default settings/passwords and start the stack.
#
#   ./run.sh              create .env if missing, build, start, wait until healthy
#   ./run.sh down         stop the stack (data is kept)
#   ./run.sh clean        stop the stack AND delete the database volume
#   ./run.sh logs         follow the Keycloak log
#   ./run.sh --reset-env  rewrite .env from the defaults, then start
#
# Defaults are for LOCAL DEVELOPMENT ONLY. Override any of them for one run by
# exporting the variable first, e.g.:
#
#   KC_BOOTSTRAP_ADMIN_PASSWORD='S3cret!' POSTGRES_PASSWORD='An0ther!' ./run.sh --reset-env
#
# An existing .env is never overwritten unless you pass --reset-env.
# =============================================================================
set -euo pipefail

# Always work from the project folder, wherever the script is called from.
cd "$(dirname "${BASH_SOURCE[0]}")"

ENV_FILE=".env"

# ----------------------------------------------------------------- defaults
# ${VAR:-default}: an exported variable wins, otherwise the default is used.
KEYCLOAK_VERSION="${KEYCLOAK_VERSION:-26.8.2}"
KC_BOOTSTRAP_ADMIN_USERNAME="${KC_BOOTSTRAP_ADMIN_USERNAME:-admin}"
KC_BOOTSTRAP_ADMIN_PASSWORD="${KC_BOOTSTRAP_ADMIN_PASSWORD:-admin}"
POSTGRES_DB="${POSTGRES_DB:-keycloak}"
POSTGRES_USER="${POSTGRES_USER:-keycloak}"
POSTGRES_PASSWORD="${POSTGRES_PASSWORD:-keycloak}"
KEYCLOAK_PORT="${KEYCLOAK_PORT:-8080}"
MAILPIT_PORT="${MAILPIT_PORT:-8025}"

# ----------------------------------------------------------------- helpers
info() { printf '\033[1;34m==>\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33mWARN:\033[0m %s\n' "$*" >&2; }
die()  { printf '\033[1;31mERROR:\033[0m %s\n' "$*" >&2; exit 1; }

# Use the Compose v2 plugin ("docker compose"); fall back to legacy docker-compose.
detect_compose() {
  command -v docker >/dev/null 2>&1 || die "docker is not installed or not on PATH."
  if docker compose version >/dev/null 2>&1; then
    COMPOSE=(docker compose)
  elif command -v docker-compose >/dev/null 2>&1; then
    COMPOSE=(docker-compose)
  else
    die "Docker Compose not found. Install the 'docker compose' plugin."
  fi
  docker info >/dev/null 2>&1 || die "Cannot reach the Docker daemon. Is Docker running?"
}

write_env() {
  # Values are written literally (no quoting), so reject characters that
  # Compose would interpret or that would break the JDBC URL / .env syntax.
  local name
  for name in KC_BOOTSTRAP_ADMIN_PASSWORD POSTGRES_PASSWORD; do
    case "${!name}" in
      *[[:space:]\$\#\'\"\\]*) die "$name must not contain spaces, \$, #, quotes or backslashes." ;;
      "") die "$name must not be empty." ;;
    esac
  done

  # Create the file private from the start: it contains passwords.
  ( umask 077
    cat > "$ENV_FILE" <<EOF
# Generated by run.sh on $(date '+%Y-%m-%d %H:%M:%S'). Local development only.
# Edit freely; run.sh will not overwrite this file unless called with --reset-env.

KEYCLOAK_VERSION=${KEYCLOAK_VERSION}

KC_BOOTSTRAP_ADMIN_USERNAME=${KC_BOOTSTRAP_ADMIN_USERNAME}
KC_BOOTSTRAP_ADMIN_PASSWORD=${KC_BOOTSTRAP_ADMIN_PASSWORD}

POSTGRES_DB=${POSTGRES_DB}
POSTGRES_USER=${POSTGRES_USER}
POSTGRES_PASSWORD=${POSTGRES_PASSWORD}

KEYCLOAK_PORT=${KEYCLOAK_PORT}
MAILPIT_PORT=${MAILPIT_PORT}
EOF
  )
  info "Wrote $ENV_FILE"
  if [[ "$KC_BOOTSTRAP_ADMIN_PASSWORD" == "admin" || "$POSTGRES_PASSWORD" == "keycloak" ]]; then
    warn "Using default passwords. Fine on your own machine, never for a shared or public host."
  fi
}

# Read one value back from .env (the file, not this script, is the source of truth).
env_value() { sed -n "s/^$1=//p" "$ENV_FILE" | tail -n 1; }

ensure_env() {
  if [[ -f "$ENV_FILE" && "$RESET_ENV" != "true" ]]; then
    info "Using existing $ENV_FILE (pass --reset-env to regenerate it)"
    return
  fi
  if [[ -f "$ENV_FILE" ]]; then
    # The database keeps the password it was created with. Changing it in .env
    # afterwards would lock Keycloak out, so point that out.
    warn "Regenerating $ENV_FILE. If POSTGRES_PASSWORD changed, run './run.sh clean' first (this deletes the database)."
  fi
  write_env
}

up() {
  ensure_env
  info "Building the provider image and starting the stack (first run takes a few minutes)"
  # --build : recompile the Java provider / theme jar if anything under provider/ changed
  # -d      : run in the background
  # --wait  : return only when the containers report healthy (uses the healthchecks)
  if ! "${COMPOSE[@]}" up --build -d --wait; then
    "${COMPOSE[@]}" ps || true
    die "Stack did not become healthy. Inspect with: ./run.sh logs"
  fi

  local kc_port mail_port
  kc_port="$(env_value KEYCLOAK_PORT)";  kc_port="${kc_port:-8080}"
  mail_port="$(env_value MAILPIT_PORT)"; mail_port="${mail_port:-8025}"

  cat <<EOF

Keycloak is up.

  Test login     http://localhost:${kc_port}/realms/acme/account    user: alice  password: alice
  Code e-mails   http://localhost:${mail_port}
  Admin console  http://localhost:${kc_port}/admin    user: $(env_value KC_BOOTSTRAP_ADMIN_USERNAME)  password: $(env_value KC_BOOTSTRAP_ADMIN_PASSWORD)

  Edit themes/acme-local/... and reload the browser to see theme changes.
  Stop: ./run.sh down     Logs: ./run.sh logs     Wipe database: ./run.sh clean
EOF
}

# ----------------------------------------------------------------- arguments
RESET_ENV="false"
COMMAND="up"
for arg in "$@"; do
  case "$arg" in
    --reset-env)         RESET_ENV="true" ;;
    up|down|clean|logs)  COMMAND="$arg" ;;
    -h|--help)           sed -n '2,17p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *)                   die "Unknown argument: $arg (try --help)" ;;
  esac
done

detect_compose

case "$COMMAND" in
  up)    up ;;
  down)  "${COMPOSE[@]}" down ;;
  clean) warn "Deleting containers and the database volume."
         "${COMPOSE[@]}" down --volumes --remove-orphans ;;
  logs)  "${COMPOSE[@]}" logs -f keycloak ;;
esac
